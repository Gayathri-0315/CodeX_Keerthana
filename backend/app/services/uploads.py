"""Upload validation and storage (SPEC 11): images and PDF only, 8 MB, EXIF stripped, outside the web root."""

import hashlib
import io
import uuid
from dataclasses import dataclass
from pathlib import Path

from fastapi import HTTPException
from PIL import Image, ImageOps, UnidentifiedImageError

from ..config import BACKEND_DIR

UPLOAD_DIR = BACKEND_DIR / "uploads"
MAX_BYTES = 8 * 1024 * 1024
MAX_SIDE = 1600
IMAGE_FORMATS = {"PNG": "image/png", "JPEG": "image/jpeg", "WEBP": "image/webp", "GIF": "image/gif"}


@dataclass
class Upload:
    data: bytes  # the original bytes (what the model reads)
    media_type: str
    sha256: str
    filename: str
    stored_name: str | None  # re-encoded, EXIF-free copy we serve, for images


def read_upload(raw: bytes, filename: str) -> Upload:
    if len(raw) > MAX_BYTES:
        raise HTTPException(413, "That file is over 8 MB. Use a smaller image or PDF.")
    if not raw:
        raise HTTPException(400, "That file is empty. Choose another one.")
    digest = hashlib.sha256(raw).hexdigest()
    name = Path(filename or "upload").name

    if raw[:5] == b"%PDF-":
        return Upload(raw, "application/pdf", digest, name, None)

    try:
        img = Image.open(io.BytesIO(raw))
        fmt = img.format
        img.load()
    except (UnidentifiedImageError, OSError):
        raise HTTPException(415, "Upload a PNG, JPEG, WebP or PDF file.")
    if fmt not in IMAGE_FORMATS:
        raise HTTPException(415, "Upload a PNG, JPEG, WebP or PDF file.")

    # Re-encoding drops EXIF and any other metadata; transpose first so phone photos stay upright.
    clean = ImageOps.exif_transpose(img).convert("RGB")
    clean.thumbnail((MAX_SIDE, MAX_SIDE))
    UPLOAD_DIR.mkdir(exist_ok=True)
    stored = f"{uuid.uuid4().hex}.webp"
    clean.save(UPLOAD_DIR / stored, "WEBP", quality=82, method=4)
    return Upload(raw, IMAGE_FORMATS[fmt], digest, name, stored)


def public_url(stored_name: str | None) -> str | None:
    return f"/api/files/{stored_name}" if stored_name else None


def file_path(stored_name: str) -> Path | None:
    # Names are generated by us (hex + .webp); anything else is not ours to serve.
    if not stored_name.endswith(".webp") or not stored_name[:-5].isalnum():
        return None
    p = UPLOAD_DIR / stored_name
    return p if p.is_file() else None
