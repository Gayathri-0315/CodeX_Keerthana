"""Upload validation and storage (SPEC 11): images and PDF only, 8 MB, EXIF stripped.

Poster images are kept in the database (table `stored_files`), not on local disk, because free hosts
wipe the disk on every redeploy. Timetable photos are read and then dropped; they are never stored.
"""

import hashlib
import io
import uuid
from dataclasses import dataclass
from pathlib import Path

from fastapi import HTTPException
from PIL import Image, ImageOps, UnidentifiedImageError

from sqlalchemy.orm import Session

MAX_BYTES = 8 * 1024 * 1024
MAX_SIDE = 1600
IMAGE_FORMATS = {"PNG": "image/png", "JPEG": "image/jpeg", "WEBP": "image/webp", "GIF": "image/gif"}


@dataclass
class Upload:
    data: bytes  # the original bytes (what the model reads)
    media_type: str
    sha256: str
    filename: str
    clean: bytes | None  # re-encoded, EXIF-free WebP copy, for images
    stored_name: str | None = None  # set once the clean copy is saved with store_image()


def read_upload(raw: bytes, filename: str) -> Upload:
    if len(raw) > MAX_BYTES:
        raise HTTPException(413, "That file is over 8 MB. Use a smaller image or PDF.")
    if not raw:
        raise HTTPException(400, "That file is empty. Choose another one.")
    digest = hashlib.sha256(raw).hexdigest()
    name = Path(filename or "upload").name

    if raw[:5] == b"%PDF-":
        return Upload(raw, "application/pdf", digest, name, None)

    try:
        img = Image.open(io.BytesIO(raw))
        fmt = img.format
        img.load()
    except (UnidentifiedImageError, OSError):
        raise HTTPException(415, "Upload a PNG, JPEG, WebP or PDF file.")
    if fmt not in IMAGE_FORMATS:
        raise HTTPException(415, "Upload a PNG, JPEG, WebP or PDF file.")

    # Re-encoding drops EXIF and any other metadata; transpose first so phone photos stay upright.
    clean = ImageOps.exif_transpose(img).convert("RGB")
    clean.thumbnail((MAX_SIDE, MAX_SIDE))
    buf = io.BytesIO()
    clean.save(buf, "WEBP", quality=82, method=4)
    return Upload(raw, IMAGE_FORMATS[fmt], digest, name, buf.getvalue())


def store_image(db: Session, upload: Upload) -> str | None:
    """Keep the clean copy (posters only) and return its served name."""
    from ..models import StoredFile

    if upload.clean is None:
        return None
    upload.stored_name = f"{uuid.uuid4().hex}.webp"
    db.add(StoredFile(name=upload.stored_name, content_type="image/webp", data=upload.clean))
    db.commit()
    return upload.stored_name


def public_url(stored_name: str | None) -> str | None:
    return f"/api/files/{stored_name}" if stored_name else None


def load_file(db: Session, stored_name: str):
    from ..models import StoredFile

    # Names are generated by us (hex + .webp); anything else is not ours to serve.
    if not stored_name.endswith(".webp") or not stored_name[:-5].isalnum():
        return None
    return db.get(StoredFile, stored_name)
